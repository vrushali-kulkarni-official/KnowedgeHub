"""Build the whole course from the Python content modules.

    python3 tools/build.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from render import page, act_page, index_page          # noqa: E402
import content_js, content_dom, content_project        # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ACTS = [
    {
        "dir": "01-js-basics",
        "tag": "Act 1",
        "title": "JavaScript basics for the DOM",
        "lede": "Six small steps to get comfortable with JavaScript. No framework, no build "
                "tool. Just the language, taught through things you already know.",
        "outcome": [
            "Declare values with <code>const</code> and <code>let</code>, and build strings "
            "with template literals.",
            "Write functions, and understand that callbacks are functions the browser keeps.",
            "Hold lists and dictionaries with arrays and objects.",
            "See that the DOM is a live tree of objects, and find elements in it.",
            "React to clicks, and understand what <code>this</code> and <code>event.target</code> "
            "mean.",
        ],
        "steps": content_js.STEPS,
    },
    {
        "dir": "02-dom",
        "tag": "Act 2",
        "title": "DOM manipulation",
        "lede": "Nine steps of pure DOM work: find elements, read and write them, build them, "
                "style them, delete them, listen to them, and keep your data straight.",
        "outcome": [
            "Find any element with CSS selectors you already know.",
            "Read and write text, HTML and form values safely.",
            "Create, insert, duplicate and delete elements.",
            "Manage classes, attributes and data attributes.",
            "Handle clicks, form submits and keystrokes with event delegation.",
            "Keep state in JavaScript and render the DOM from it &mdash; the React mindset.",
        ],
        "steps": content_dom.STEPS,
    },
    {
        "dir": "03-project",
        "tag": "Act 3",
        "title": "Put it together: a project",
        "lede": "One real app, built from everything above. Then a code review, and a look at "
                "how much smaller the same app becomes in React.",
        "outcome": [
            "Build a working todo app with add, toggle, delete, counter and persistence.",
            "Review DOM code with the five questions that catch almost every bug.",
            "See the state + render pattern inside React, and know you already have the hard "
            "part.",
        ],
        "steps": content_project.STEPS,
    },
]


def build():
    # normalise step metadata
    all_steps = []
    for a in ACTS:
        a["count"] = len(a["steps"])
        for i, s in enumerate(a["steps"], 1):
            s["no"] = i
            s["href"] = "%02d-%s.html" % (i, s["id"])
            s["path"] = os.path.join(ROOT, a["dir"], "steps", s["href"])
            all_steps.append((a, s))

    # prev / next across the whole course
    for idx, (a, s) in enumerate(all_steps):
        s["prev"] = all_steps[idx - 1][1] if idx > 0 else None
        s["next"] = all_steps[idx + 1][1] if idx + 1 < len(all_steps) else None

    written = []

    for a in ACTS:
        adir = os.path.join(ROOT, a["dir"])
        os.makedirs(os.path.join(adir, "steps"), exist_ok=True)

        for s in a["steps"]:
            # relative link that also works across act boundaries
            def link_to(neighbour):
                if not neighbour:
                    return None
                rel = os.path.relpath(neighbour["path"], os.path.join(adir, "steps"))
                return {"href": rel.replace(os.sep, "/"), "title": neighbour["title"]}

            html_text = page(s, a, link_to(s.get("prev")), link_to(s.get("next")), None)
            with open(s["path"], "w", encoding="utf-8") as f:
                f.write(html_text)
            written.append(s["path"])

        lesson = act_page(a, a["steps"])
        with open(os.path.join(adir, "lesson.html"), "w", encoding="utf-8") as f:
            f.write(lesson)
        written.append(os.path.join(adir, "lesson.html"))

    with open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8") as f:
        f.write(index_page(ACTS))
    written.append(os.path.join(ROOT, "index.html"))

    # ---- ROADMAP.md
    lines = [
        "# Roadmap",
        "",
        "Your progress board. Tick the box at the bottom of a step page in your browser - "
        "the course map and this file both track it (the file is regenerated by "
        "`python3 tools/build.py`).",
        "",
    ]
    total = 0
    for a in ACTS:
        lines.append("## %s - %s" % (a["tag"], a["title"]))
        lines.append("")
        lines.append("> %s" % a["lede"])
        lines.append("")
        for s in a["steps"]:
            lines.append("- [ ] **Step %d - %s** &nbsp; `(%s/steps/%s)`"
                         % (s["no"], s["title"], a["dir"], s["href"]))
        lines.append("")
        total += a["count"]
    lines.append("---")
    lines.append("")
    lines.append("**%d steps** across %d acts. Start here: "
                 "`01-js-basics/steps/01-js-variables.html`" % (total, len(ACTS)))
    lines.append("")
    with open(os.path.join(ROOT, "ROADMAP.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    written.append(os.path.join(ROOT, "ROADMAP.md"))

    # ---- README.md
    readme = """# Frontend Journey - DOM Manipulation

A self-paced course for someone who already knows **HTML and CSS**, knows **Python**,
and knows **zero JavaScript** - and wants to learn DOM manipulation properly.

## How to use it

Open `index.html` in your browser. That is the map. Everything is static HTML, so no
server, no install, no build step.

Each step page has:

- **The idea** - the concept, explained in plain language, with a Python bridge
- **Live demo** - a working example you can click
- **Your turn (lab)** - a small editor with a Run button, like the Python REPL
- **Tiny challenge** - one small thing to build yourself
- **Checkpoint** - what you should be able to explain now

Tick the box at the bottom of each step. Your progress is saved in the browser
(`localStorage`), and the course map shows it.

## The path

| Act | What it covers | Steps |
|-----|----------------|-------|
""" + "\n".join(
        "| %s | %s | %d |\n" % (a["tag"], a["title"], a["count"]) for a in ACTS
    ) + """
## The one rule of this course

Never move to the next step while something is still a mystery. Ask, fix it, then move on.

## Rebuilding

Course content lives in Python data files under `tools/`:

```
tools/render.py          page templates + syntax highlighting
tools/content_js.py      Act 1 - JavaScript basics
tools/content_dom.py     Act 2 - DOM manipulation
tools/content_project.py Act 3 - the project
tools/build.py           renders everything to HTML
```

Edit a content file, then:

```bash
python3 tools/build.py
```
"""
    with open(os.path.join(ROOT, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme)
    written.append(os.path.join(ROOT, "README.md"))

    print("built %d files" % len(written))
    for p in written:
        print("  " + os.path.relpath(p, ROOT))


if __name__ == "__main__":
    build()
